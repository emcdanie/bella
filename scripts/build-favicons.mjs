#!/usr/bin/env node
// Brand favicons (brand refresh, 2026-09-22; Elleta picked option 3 in
// docs/reference/favicon-options.html): the pattern E on cream, rounded,
// with a 1px ochre-deep edge so it holds on light tabs. A FIXED seed, so the
// pattern never changes between builds. Also the ink BELLA wordmark the
// Storybook sidebar lockup shows.
//
//   node scripts/build-favicons.mjs --svg-only   SVGs only (part of npm run build;
//                                                deterministic, diffed by the gate)
//   node scripts/build-favicons.mjs              SVGs + 16/32 PNG, favicon.ico,
//                                                apple-touch-icon 180, icon-512
//                                                (npm run build:favicons; raster output
//                                                varies by platform, so not in the gate)

import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { patternShapesWith, GLYPHS, LOCK, wordPaths } from '../src/brand/pattern-core.mjs';

const SEED = 7;
const STROKE = LOCK.weight * 2; /* 2x the wordmark weight: ~2.5px at 16, still clears the low-line counter (2026-09-22) */
const tokens = JSON.parse(readFileSync('tokens/bella.json', 'utf8'));
const P = tokens.primitive.color.pattern;
const val = (t) => t.$value;
const COLORS = {
  ochre: val(P.ground), blue: val(P.tiger), cream: val(P.cream), pale: val(P.rosette), pink: val(P.pink),
  leaf: val(P.leopard), lime: val(P.zebra), limeL: val(P['zebra-light']), ink: val(P.ink), coral: val(P.coral),
};
const EDGE = val(tokens.primitive.color.brand['ochre-deep']);
const INK = val(tokens.primitive.color.light.ink);

const shapesSvg = (shapes) =>
  shapes
    .map((s) =>
      s.stroke
        ? `<path d="${s.d}" fill="none" stroke="${s.stroke}" stroke-width="${s.strokeWidth}" stroke-linecap="round"/>`
        : `<path d="${s.d}" fill="${s.fill}"/>`
    )
    .join('');

/** The favicon: glyph E, stroke STROKE (heavier than the wordmark so it holds at 16px), centred in a
 * rounded cream square, with an edge of `edgePx` device pixels at `sizePx`. */
function faviconSvg(sizePx = 16, edgePx = 1, weight = STROKE) {
  const g = GLYPHS.E;
  const sx = LOCK.width / 100;
  const sy = LOCK.height / 100;
  const sw = weight; /* lay the E out for the stroke it is drawn with */
  const W = g.w * sx + sw;
  const H = 100 * sy;
  const S = Math.max(W, H) + 24;
  const ox = (S - W) / 2;
  const oy = (S - H) / 2;
  const Y = (v) => (v <= 0 ? 0 : v >= 100 ? 100 * sy : sw / 2 + ((v - 10) * (100 * sy - sw)) / 80);
  const d = g.d.replace(/([MLHVQ])([^MLHVQ]*)/g, (_m, c, a) => {
    const n = a.trim().split(/[\s,]+/).filter(Boolean).map(Number);
    if (c === 'H') return `H${(n[0] * sx + sw / 2).toFixed(1)} `;
    if (c === 'V') return `V${Y(n[0]).toFixed(1)} `;
    return `${c}${n.map((v, i) => (i % 2 ? Y(v).toFixed(1) : (v * sx + sw / 2).toFixed(1))).join(' ')} `;
  });
  const edge = (S / sizePx) * edgePx;
  const r = S * 0.22;
  const pattern = shapesSvg(patternShapesWith(S * 4, S * 4, SEED, COLORS));
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${S.toFixed(1)} ${S.toFixed(1)}">
<!-- Generated by scripts/build-favicons.mjs (seed ${SEED}). Do not edit by hand. -->
<defs><clipPath id="c"><rect width="${S.toFixed(1)}" height="${S.toFixed(1)}" rx="${r.toFixed(1)}"/></clipPath>
<mask id="m" maskUnits="userSpaceOnUse" x="0" y="0" width="${S.toFixed(1)}" height="${S.toFixed(1)}"><rect width="${S.toFixed(1)}" height="${S.toFixed(1)}" fill="black"/><g transform="translate(${ox.toFixed(1)} ${oy.toFixed(1)})" fill="none" stroke="white" stroke-width="${weight}" stroke-linejoin="round"><path d="${d.trim()}"/></g></mask></defs>
<g clip-path="url(#c)"><rect width="${S.toFixed(1)}" height="${S.toFixed(1)}" fill="${COLORS.cream}"/>
<g mask="url(#m)"><g transform="scale(0.25)">${pattern}</g></g></g>
<rect x="${(edge / 2).toFixed(2)}" y="${(edge / 2).toFixed(2)}" width="${(S - edge).toFixed(2)}" height="${(S - edge).toFixed(2)}" rx="${(r - edge / 2).toFixed(2)}" fill="none" stroke="${EDGE}" stroke-width="${edge.toFixed(2)}"/>
</svg>
`;
}

/** The ink BELLA wordmark for the Storybook sidebar lockup. */
function wordmarkInkSvg(word = 'BELLA') {
  const { paths, width, height, strokeWidth } = wordPaths(word);
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width.toFixed(1)} ${height}" role="img" aria-label="${word}">
<!-- Generated by scripts/build-favicons.mjs. Do not edit by hand. -->
<g fill="none" stroke="${INK}" stroke-width="${strokeWidth}" stroke-linejoin="round">${paths.map((p) => `<path d="${p.trim()}"/>`).join('')}</g>
</svg>
`;
}

const OUT = 'src/assets/brand/favicon';
mkdirSync(OUT, { recursive: true });
mkdirSync('.storybook/public/brand', { recursive: true });
const favicon = faviconSvg(16, 1);
writeFileSync(`${OUT}/favicon.svg`, favicon);
writeFileSync('.storybook/public/favicon.svg', favicon);
writeFileSync('.storybook/public/brand/bella-wordmark-ink.svg', wordmarkInkSvg('BELLA'));

if (process.argv.includes('--svg-only')) {
  console.log('favicons: svg written (seed 7)');
  process.exit(0);
}

/* Rasterise each size from an SVG whose edge is exactly 1 device pixel at
 * that size, then pack favicon.ico from the 16 and 32 PNGs. */
const { chromium } = await import('playwright');
const browser = await chromium.launch();
const page = await browser.newPage({ deviceScaleFactor: 1 });
const png = {};
for (const [name, size] of [
  ['favicon-16.png', 16],
  ['favicon-32.png', 32],
  ['apple-touch-icon.png', 180],
  ['icon-512.png', 512],
]) {
  const svg = faviconSvg(size, 1);
  await page.setViewportSize({ width: size, height: size });
  await page.setContent(
    `<html><body style="margin:0;background:transparent"><img width="${size}" height="${size}" src="data:image/svg+xml;base64,${Buffer.from(svg).toString('base64')}"></body></html>`
  );
  await page.waitForFunction(() => document.images[0]?.complete);
  const buf = await page.locator('img').screenshot({ omitBackground: true });
  writeFileSync(`${OUT}/${name}`, buf);
  png[size] = buf;
}
await browser.close();

const entries = [16, 32].map((s) => ({ s, data: png[s] }));
const header = Buffer.alloc(6 + 16 * entries.length);
header.writeUInt16LE(0, 0);
header.writeUInt16LE(1, 2);
header.writeUInt16LE(entries.length, 4);
let offset = header.length;
entries.forEach(({ s, data }, i) => {
  const o = 6 + i * 16;
  header.writeUInt8(s, o);
  header.writeUInt8(s, o + 1);
  header.writeUInt8(0, o + 2);
  header.writeUInt8(0, o + 3);
  header.writeUInt16LE(1, o + 4);
  header.writeUInt16LE(32, o + 6);
  header.writeUInt32LE(data.length, o + 8);
  header.writeUInt32LE(offset, o + 12);
  offset += data.length;
});
writeFileSync(`${OUT}/favicon.ico`, Buffer.concat([header, ...entries.map((e) => e.data)]));
console.log(`favicons: svg + 16/32 png, favicon.ico, apple-touch-icon 180, icon-512 in ${OUT} (seed ${SEED})`);
